def lookup_vendor(mac):
    """Look up vendor name for a MAC address from embedded registry."""
    norm = normalize_mac(mac)
    if not norm:
        return "Bilinmiyor"
    oui = norm[:8]
    return OUI_REGISTRY.get(oui, "Bilinmiyor")